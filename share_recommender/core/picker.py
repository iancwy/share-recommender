"""The AI picker: what Claude is sent, the shape of its answer, and the checks on that answer.

Pure functions. The call itself is in ``ai/picker.py``. Claude's answer is never trusted
blindly: ``check`` drops anything not on the goal's shortlist, fixes actions that don't fit
(a "hold" on something the person doesn't own), keeps at most five buy ideas per goal,
scales suggested weights down to the goal's room for individual shares and fills in any held
or watchlist item Claude left out.
"""

from dataclasses import dataclass
from datetime import date, datetime
from decimal import Decimal
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, Field

from share_recommender.core.models import Category
from share_recommender.core.preferences import CategoryPreferences, InvestorPreferences
from share_recommender.core.recommender import Recommendation
from share_recommender.core.screen import Key, Shortlist, ShortlistItem
from share_recommender.core.universe import Kind

AI_DISCLAIMER = ("Picks are generated by AI from a rules-based screen. They can be wrong or out "
                 "of date, and they're general information, not personal financial advice.")

MAX_BUYS = 5
TEXT_LIMIT = 300                       # characters of provider text (names, summaries)
BLOCKING_FILTERS = {"exclusions", "bonds", "etf_only"}  # never a buy, even if held or watched
NOT_RANKED = "Not ranked by Claude this time."

Action = Literal["buy", "hold", "review", "watch"]
Conviction = Literal["high", "medium", "low"]


# Claude's answer ----------------------------------------------------------------------

class AIPick(BaseModel):
    ticker: str
    exchange: str
    action: Action
    conviction: Conviction
    rank: int = Field(ge=1, le=50)
    suggested_weight: Decimal | None = Field(default=None, ge=0, le=100)  # % of the goal
    rationale: str = Field(max_length=1200)
    risks: str = Field(max_length=400)


class GoalPicks(BaseModel):
    goal: str                       # "g1", "g2", …
    summary: str = Field(max_length=600)
    picks: list[AIPick]


class PickerOutput(BaseModel):
    goals: list[GoalPicks]


# What Claude is sent --------------------------------------------------------------------

@dataclass(frozen=True)
class PickerGoal:
    """Everything about one goal the picker needs. ``key`` is "g1", "g2", … in the payload."""

    key: str
    category: Category
    prefs: CategoryPreferences
    speculative: bool
    recommendation: Recommendation
    shortlist: Shortlist
    holdings: dict[Key, Decimal]    # what the goal holds now, % of the goal


def share_room(rec: Recommendation) -> Decimal:
    """How much of the goal (%) the rules recommender sets aside for individual shares."""
    return sum((p.weight for p in rec.mix.picks if p.kind is Kind.SHARE), Decimal(0))


def _num(value: Decimal | None) -> float | None:
    return float(value) if value is not None else None


def _shortlist_item(i: ShortlistItem) -> dict:
    return {
        "ticker": i.key[0], "exchange": i.key[1], "kind": i.kind, "sector": i.sector,
        "industry": i.industry, "score": i.score, "factors": i.factors, "metrics": i.metrics,
        "source": i.source, "filter_notes": i.filter_notes,
        # From the market data provider: data, never instructions.
        "provider_text": {"name": (i.name or "")[:TEXT_LIMIT] or None,
                          "summary": (i.summary or "")[:TEXT_LIMIT] or None},
    }


def _goal(g: PickerGoal) -> dict:
    c, mix, gaps = g.category, g.recommendation.mix, g.recommendation.gaps
    biggest = sorted(gaps.slices, key=lambda s: -abs(s.difference))[:3]
    return {
        "goal": g.key,
        "name": c.name,
        "description": c.description,
        "risk_level": c.risk_level.value,
        "target_amount": _num(c.target_amount),
        "target_date": c.target_date.isoformat() if c.target_date else None,
        "years_to_go": _num(mix.horizon_years),
        "flexibility": g.prefs.flexibility.value,
        "speculative": g.speculative,
        "themes": [t.value for t in g.prefs.themes] if g.speculative else [],
        "notes": g.prefs.notes,
        "growth_pct": mix.growth_pct,
        "target_slices": [{"label": s.label, "weight_pct": float(s.weight)} for s in mix.slices],
        "room_for_individual_shares_pct": float(share_room(g.recommendation)),
        "current_mix": [{"label": s.label, "current_pct": float(s.current_pct),
                         "target_pct": float(s.target_pct)} for s in gaps.slices],
        "biggest_gaps": [{"label": s.label, "under_target_by": float(s.difference)}
                         for s in biggest if s.difference],
        "holds_now": [{"ticker": t, "exchange": e, "pct_of_goal": round(float(pct), 1)}
                      for (t, e), pct in sorted(g.holdings.items())],
        "shortlist": [_shortlist_item(i) for i in g.shortlist.items],
    }


def build_payload(inv: InvestorPreferences, base_currency: str, goals: list[PickerGoal],
                  today: date) -> dict:
    """The JSON Claude receives. No database ids, emails or anything else about the account."""
    return {
        "today": today.isoformat(),
        "investor": inv.model_dump(mode="json") | {"base_currency": base_currency},
        "goals": [_goal(g) for g in goals],
    }


# Checks on Claude's answer ---------------------------------------------------------------

@dataclass
class PickRow:
    goal_id: str
    ticker: str
    exchange: str
    name: str | None
    kind: str
    action: Action
    conviction: Conviction
    rank: int
    score: float | None
    suggested_weight: Decimal | None
    rationale: str
    risks: str | None
    metrics: dict
    source: str


def _row(goal: PickerGoal, item: ShortlistItem, pick: AIPick) -> PickRow:
    return PickRow(str(goal.category.id), item.key[0], item.key[1], item.name, item.kind,
                   pick.action, pick.conviction, pick.rank, item.score, pick.suggested_weight,
                   pick.rationale, pick.risks or None, item.metrics, item.source)


def _fix_action(pick: AIPick, item: ShortlistItem, held: bool, watched: bool
                ) -> tuple[Action | None, str | None]:
    """The action to keep (None to drop the pick) and a warning if it was changed."""
    t = f"{item.key[0]} ({item.key[1]})"
    fallback: Action | None = "hold" if held else "watch" if watched else None
    if pick.action == "buy" and BLOCKING_FILTERS & set(item.failed):
        reason = next((n for n in item.filter_notes), "it fails a rule")
        if fallback is None:
            return None, f"Claude suggested buying {t}, which a rule rules out ({reason}), " \
                         "so it was left out"
        fallback = "review" if held else fallback
        return fallback, f"Claude suggested buying {t}, but {reason.lower()}, so it's " \
                         f"shown as {fallback} instead"
    if pick.action in ("hold", "review") and not held:
        if fallback is None:
            return None, f"Claude said {pick.action} for {t}, which you don't hold, so it " \
                         "was left out"
        return fallback, f"Claude said {pick.action} for {t}, which you don't hold, so it's " \
                         f"shown as {fallback}"
    if pick.action == "watch" and (held or not watched):
        if fallback is None:
            return None, f"Claude said watch for {t}, which isn't on your watchlist, so it " \
                         "was left out"
        return "hold", f"Claude said watch for {t}, which you already hold, so it's shown " \
                       "as hold"
    return pick.action, None


def check(output: PickerOutput, goals: list[PickerGoal]) -> tuple[list[PickRow], list[str]]:
    by_key = {g.key: g for g in goals}
    answers: dict[str, list[AIPick]] = {g.key: [] for g in goals}
    warnings: list[str] = []
    for gp in output.goals:
        if gp.goal not in by_key:
            warnings.append(f"Claude answered for a goal it wasn't given ({gp.goal}), so "
                            f"{len(gp.picks)} suggestion(s) were left out")
            continue
        answers[gp.goal].extend(gp.picks)

    rows: list[PickRow] = []
    for goal in goals:
        items = {i.key: i for i in goal.shortlist.items}
        held = {i.key for i in goal.shortlist.items if i.source == "held"}
        watched = {i.key for i in goal.shortlist.items if i.source == "watchlist"}
        kept: list[PickRow] = []
        seen: set[Key] = set()
        buys = 0
        for pick in sorted(answers[goal.key], key=lambda p: (p.rank, p.ticker)):
            key = (pick.ticker.strip().upper(), pick.exchange.strip().upper())
            item = items.get(key)
            if item is None:
                warnings.append(f"Claude suggested {key[0]} ({key[1]}), which wasn't on the "
                                f"shortlist for {goal.category.name}, so it was left out")
                continue
            if key in seen:
                continue
            action, warning = _fix_action(pick, item, key in held, key in watched)
            if action == "buy":
                if buys >= MAX_BUYS:
                    action = "hold" if key in held else "watch" if key in watched else None
                    warning = None if action else (
                        f"Claude suggested more than {MAX_BUYS} buy ideas for "
                        f"{goal.category.name}, so {key[0]} was left out")
                else:
                    buys += 1
            if warning:
                warnings.append(warning)
            if action is None:
                continue
            seen.add(key)
            kept.append(_row(goal, item, pick.model_copy(update={"action": action})))

        for key in sorted(held | watched):  # anything Claude left out
            if key not in seen:
                action = "hold" if key in held else "watch"
                kept.append(_row(goal, items[key], AIPick(
                    ticker=key[0], exchange=key[1], action=action, conviction="low", rank=50,
                    rationale=NOT_RANKED, risks="")))

        room = share_room(goal.recommendation)
        for r in kept:
            if r.action != "buy":
                r.suggested_weight = None
        total = sum((r.suggested_weight or Decimal(0) for r in kept), Decimal(0))
        if total > room:
            for r in kept:
                if r.suggested_weight is not None:
                    r.suggested_weight = (r.suggested_weight * room / total).quantize(
                        Decimal("0.01"))
            warnings.append(f"Claude's suggested weights for {goal.category.name} added up to "
                            f"{total:g}%, more than the {room:g}% set aside for individual "
                            "shares, so they were scaled down")
        for n, r in enumerate(kept, start=1):
            r.rank = n
        rows.extend(kept)
    return rows, warnings


def summaries(output: PickerOutput, goals: list[PickerGoal]) -> dict[str, str]:
    """Claude's summary per goal, keyed by category id."""
    ids = {g.key: str(g.category.id) for g in goals}
    return {ids[gp.goal]: gp.summary for gp in output.goals if gp.goal in ids}


# Saved runs ------------------------------------------------------------------------------

class PickRun(BaseModel):
    """One run of the picker: what was screened, Claude's token use and per-goal summaries."""

    id: UUID | None = None
    trigger: Literal["manual", "scheduled"]
    status: Literal["ok", "failed"] = "ok"
    model: str | None = None
    input_hash: str | None = None
    pool_size: int = 0
    shortlisted: int = 0
    input_tokens: int | None = None
    output_tokens: int | None = None
    # {"goals": {category id: {"name", "summary", "counts"}}, "warnings": [...],
    #  "skipped": [...]}
    summary: dict = Field(default_factory=dict)
    error: str | None = None
    created_at: datetime | None = None

    def record(self) -> dict:
        """The columns to insert (the database fills id, user_id and created_at)."""
        return self.model_dump(mode="json", exclude={"id", "created_at"})


def pick_record(row: PickRow, run_id: str) -> dict:
    return {"run_id": run_id, "category_id": row.goal_id or None, "ticker": row.ticker,
            "exchange": row.exchange, "name": row.name, "kind": row.kind,
            "action": row.action, "conviction": row.conviction, "rank": row.rank,
            "score": row.score,
            "suggested_weight": str(row.suggested_weight)
            if row.suggested_weight is not None else None,
            "rationale": row.rationale, "risks": row.risks, "metrics": row.metrics,
            "source": row.source}


def pick_from_record(r: dict) -> PickRow:
    weight = r.get("suggested_weight")
    score = r.get("score")
    return PickRow(str(r["category_id"]) if r.get("category_id") else "", r["ticker"],
                   r["exchange"], r.get("name"), r.get("kind") or "share", r["action"],
                   r["conviction"], int(r["rank"]), float(score) if score is not None else None,
                   Decimal(str(weight)) if weight is not None else None, r["rationale"],
                   r.get("risks"), r.get("metrics") or {}, r["source"])
